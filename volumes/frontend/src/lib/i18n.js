const DICTIONARIES = { fr, es };

// The language in use, readable outside React (error messages built in the API client).
// Known from the start, so that nothing rendered before the provider settles is in the wrong one.
let currentLanguage = initialLanguage();

export function normalizeLanguage(code) {
  const short = String(code || "").toLowerCase().slice(0, 2);
  return SUPPORTED.includes(short) ? short : null;
}

/** The language to start with: the last one used here, else the browser's, else English. */
export function initialLanguage() {
  try {
    const stored = normalizeLanguage(localStorage.getItem(STORAGE_KEY));
    if (stored) return stored;
  } catch {
    // Storage unavailable (private window): the browser's language will do.
  }
  return normalizeLanguage(navigator.language) || "en";
}

export function rememberLanguage(language) {
  currentLanguage = language;
  document.documentElement.lang = language;
  try {
    localStorage.setItem(STORAGE_KEY, language);
  } catch {
    // Not remembered between visits, nothing worse.
  }
}

export function getLanguage() {
  return currentLanguage;
}

function fill(text, params) {
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

/** The sentence `key` in `language`, with its placeholders filled; English when there is no translation. */
export function translate(language, key, params) {
  const dictionary = DICTIONARIES[language];
  return fill((dictionary && dictionary[key]) || key, params);
}

/** translate() in the language currently in use. */
export function t(key, params) {
  return translate(currentLanguage, key, params);
}

/** The name of a language in the language currently shown, e.g. "fr" -> "français" on a French page. */
export function languageName(code, language = currentLanguage) {
  try {
    return new Intl.DisplayNames([language], { type: "language" }).of(code) || code;
  } catch {
    return code;
  }
}
